const path=require('path');
const assert=require('assert/strict');
const {pathToFileURL}=require('url');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'C:/Users/Unmesh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');

(async()=>{
  const file=path.resolve(__dirname,'../dist/Swara-Institute-Sharable.html');
  const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(pathToFileURL(file).href);
  await page.evaluate(()=>{
    db.trainers.push({id:'qa-trainer',name:'Pandit Test',mobile:'9000000000',email:'pandit@example.test',location:'Pune',expertise:'Hindustani vocal',availability:'Monday evenings',commission:20,status:'Active'});
    render();
  });
  await page.locator('.nav [data-page="more"]').click();
  await page.getByRole('button',{name:/Profile search/}).click();
  await page.locator('#directory-search').fill('Tanya Wells');
  await page.waitForTimeout(300);
  const studentTable=page.locator('.directory-results').filter({has:page.getByRole('heading',{name:'Students'})});
  assert.equal(await studentTable.locator('tbody tr').count(),1);
  const studentText=await studentTable.innerText();
  assert.ok(studentText.includes('Tanya Wells'));
  assert.ok(studentText.includes('Floating'));
  assert.ok(studentText.includes('Online'));
  await page.locator('#directory-status').selectOption('Active');
  assert.equal(await studentTable.locator('tbody tr').count(),1);
  await page.locator('#directory-search').fill('');
  await page.waitForTimeout(300);
  await page.locator('#directory-status').selectOption('Paused');
  assert.equal(await studentTable.locator('tbody tr').count(),18);
  await page.locator('#directory-type').selectOption('trainers');
  assert.equal(await page.locator('#directory-status').inputValue(),'');
  await page.locator('#directory-search').fill('Hindustani vocal');
  await page.waitForTimeout(300);
  await page.locator('#directory-status').selectOption('Active');
  const trainerTable=page.locator('.directory-results').filter({has:page.getByRole('heading',{name:'Trainers'})});
  assert.equal(await trainerTable.locator('tbody tr').count(),1);
  const trainerText=await trainerTable.innerText();
  assert.ok(trainerText.includes('Pandit Test'));
  assert.ok(trainerText.includes('9000000000'));
  assert.ok(trainerText.includes('Monday evenings'));
  await trainerTable.scrollIntoViewIfNeeded();
  await page.screenshot({path:path.resolve(__dirname,'../dist/qa-profile-search.png')});
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS student and trainer search filters by text, profile type and status in tabular format.');
})().catch(error=>{console.error(error);process.exit(1);});
